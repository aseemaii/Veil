export function passesVerhoeff(value: string): boolean {
  const digits = value.replace(/\D/g, '');
  if (digits.length !== 12) return false;
  let checksum = 0;
  const reversed = [...digits].reverse().map(Number);
  for (let index = 0; index < reversed.length; index += 1) {
    const digit = reversed[index];
    const row = permutation[index % 8];
    if (digit === undefined || row === undefined) return false;
    checksum = multiplication[checksum]?.[row[digit] ?? -1] ?? -1;
  }
  return checksum === 0;
}

export function passesIban(value: string): boolean {
  const compact = value.replace(/\s+/g, '').toUpperCase();
  if (!/^[A-Z]{2}\d{2}[A-Z0-9]{11,30}$/.test(compact)) return false;
  const rearranged = compact.slice(4) + compact.slice(0, 4);
  let remainder = 0;
  for (const character of rearranged) {
    const expanded = character >= 'A' ? String(character.charCodeAt(0) - 55) : character;
    for (const digit of expanded) remainder = (remainder * 10 + Number(digit)) % 97;
  }
  return remainder === 1;
}
